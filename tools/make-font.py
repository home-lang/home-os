CELL_W, CELL_H = 8, 16
# Where the 7 authored rows sit inside the 16-row cell: three rows of leading
# above, so descenders on g/j/p/q/y have somewhere to go below the baseline.
TOP = 4
LEFT = 1


def cell(rows):
    """Expand a 5x7 glyph into 16 bytes, one per row, MSB leftmost."""
    out = bytearray(CELL_H)
    for y, row in enumerate(rows):
        bits = 0
        for x, c in enumerate(row):
            if c == '#':
                bits |= 1 << (7 - (LEFT + x))
        out[TOP + y] = bits
    return bytes(out)


def build():
    glyphs = bytearray()
    for code in range(256):
        ch = chr(code)
        rows = G.get(ch)
        if rows is None:
            # Undefined codes render blank rather than as a placeholder box:
            # a boot log full of boxes is harder to read than one with gaps.
            glyphs += bytes(CELL_H)
        else:
            glyphs += cell(rows)
    return bytes(glyphs)


def psf2(glyphs):
    # PSF2: magic, version, header size, flags, glyph count, bytes per glyph,
    # height, width. No unicode table — the console indexes by byte.
    header = struct.pack('<IIIIIIII',
                         0x864AB572, 0, 32, 0, 256, CELL_H, CELL_H, CELL_W)
    return header + glyphs


def preview(text):
    for y in range(CELL_H):
        line = ''
        for ch in text:
            row = cell(G[ch])[y] if ch in G else 0
            line += ''.join('#' if row & (1 << (7 - x)) else '.'
                            for x in range(CELL_W))
        print(line)


if __name__ == '__main__':
    data = psf2(build())
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, 'assets', 'fonts', 'default.psf')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'wb') as f:
        f.write(data)
    print(f'wrote {out}: {len(data)} bytes, {len(G)} glyphs defined')
